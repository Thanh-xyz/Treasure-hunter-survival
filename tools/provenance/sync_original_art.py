#!/usr/bin/env python3
"""Upsert `original` manifest records for art IDs declared in sense/art/*.gd.

    python3 -I tools/provenance/sync_original_art.py          # write
    python3 -I tools/provenance/sync_original_art.py --check  # exit 1 if records are missing

IDs are read from the GDScript sources (no Godot needed):
  - sense/art/ui_icons.gd   ICONS keys          -> ui.icon.<name>
  - sense/art/ui_kit.gd     PATTERNS keys, RARITY_NAMES (ui.frame.slot.<name>), texture_ids()
Records point at the declaring source file; ArtCatalogTests checks every ID resolves.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "docs/architecture/asset-manifest.json"


def block(text: str, start: str) -> str:
    i = text.index(start)
    opener = min(k for k in (text.find("{", i), text.find("[", i)) if k >= 0)
    depth = 0
    for j in range(opener, len(text)):
        if text[j] in "{[":
            depth += 1
        elif text[j] in "}]":
            depth -= 1
            if depth == 0:
                return text[i:j + 1]
    raise ValueError(f"unterminated block {start}")


def declared_ids() -> dict[str, dict]:
    ids: dict[str, dict] = {}
    icons_src = (ROOT / "sense/art/ui_icons.gd").read_text(encoding="utf-8")
    for name in re.findall(r'^\t"(\w+)": \[', block(icons_src, "const ICONS"), re.M):
        ids[f"ui.icon.{name}"] = {"category": "ui_icon", "target_path": "sense/art/ui_icons.gd",
                                  "file_format": "gdscript_ascii_sprite", "dimensions": [16, 16]}
    kit_src = (ROOT / "sense/art/ui_kit.gd").read_text(encoding="utf-8")
    for name in re.findall(r'^\t"(ui\.[\w.]+)": \{', block(kit_src, "const PATTERNS"), re.M):
        ids[name] = {"category": "ui_style", "target_path": "sense/art/ui_kit.gd",
                     "file_format": "gdscript_9slice_pattern", "dimensions": None}
    for name in re.findall(r'"(\w+)"', block(kit_src, "const RARITY_NAMES")):
        ids[f"ui.frame.slot.{name}"] = {"category": "ui_style", "target_path": "sense/art/ui_kit.gd",
                                        "file_format": "gdscript_9slice_pattern", "dimensions": [8, 8]}
    tex_fn = kit_src[kit_src.index("static func texture_ids()"):]
    for name in re.findall(r'"(ui\.[\w.]+)"', tex_fn[:tex_fn.index("\n\n")]):
        ids[name] = {"category": "ui_texture", "target_path": "sense/art/ui_kit.gd",
                     "file_format": "gdscript_generated", "dimensions": None}
    return ids


def record(asset_id: str, info: dict, today: str) -> dict:
    return {
        "asset_id": asset_id,
        "category": info["category"],
        "source_path": None,
        "target_path": info["target_path"],
        "file_format": info["file_format"],
        "dimensions": info["dimensions"],
        "transparency": "transparent_or_partial",
        "animation": None,
        "usage": [],
        "provenance": {
            "status": "original",
            "source": f"in-repo: {info['target_path']}",
            "creator": "Cinderwild project",
            "license": "Project-owned",
            "license_ref": None,
            "commercial_use": "yes",
            "modification": "yes",
            "attribution": None,
            "distribution_restrictions": None,
            "verified_by": "repository history",
            "verified_on": today,
        },
        "evidence_status": "source_inspected",
        "integration_status": "available",
        "notes": ["Generated by tools/provenance/sync_original_art.py; drawn per docs/design/ART_BIBLE.md."],
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Sync original art IDs into the asset manifest")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    data = json.loads(MANIFEST.read_text(encoding="utf-8"))
    existing = {r["asset_id"] for r in data["assets"]}
    declared = declared_ids()
    missing = [i for i in sorted(declared) if i not in existing]
    if args.check:
        for i in missing:
            print(f"missing manifest record: {i}")
        return 1 if missing else 0
    today = date.today().isoformat()
    data["assets"].extend(record(i, declared[i], today) for i in missing)
    MANIFEST.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"declared {len(declared)} art ids; added {len(missing)} records")
    return 0


if __name__ == "__main__":
    sys.exit(main())
